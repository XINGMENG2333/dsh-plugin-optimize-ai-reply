    "2 改句式：翻案腔→直接说结论；段首零回指→补“这”或并入上段；提示性冒号与空转句→删引导语；翻译腔五种；起手式（说白了/说穿了）。",
    "3 改语言逻辑：按第二节重排命中段落的信息流、拆合句子、换动词、重写连接方式。",
